#!/usr/bin/env bun
// SP-0170: regenerate migrations/0820_customer_master_reference.sql from the committed client
// JSON. Deterministic; `bun packages/db/scripts/build-customer-reference-sql.js --check` fails
// when the committed migration differs from the JSON (the test suite runs the same check).
import { resolve } from "node:path";
import {
  REFERENCE_LISTS,
  REFERENCE_SOURCE,
  readReferenceJson,
  referenceRows,
} from "../src/customer-reference.js";

export const MIGRATION = resolve(
  import.meta.dir,
  "../migrations/0820_customer_master_reference.sql",
);

/** @param {string} v */
const lit = (v) => `'${String(v).replaceAll("'", "''")}'`;

export async function buildSql() {
  const rows = referenceRows(await readReferenceJson());
  const values = rows
    .map(
      (r) =>
        `  (${[r.list, r.salesOrgCode, r.channelCode, r.group1Code, r.code, r.name].map(lit).join(",")},${r.sortOrder})`,
    )
    .join(",\n");
  return `-- 0820_customer_master_reference (SP-0170). GENERATED by
-- packages/db/scripts/build-customer-reference-sql.js from
-- packages/db/reference/sunpride-customer-master-2026-11-10.json — do not hand-edit.
-- Source: Sunpride MIS/IT (Loren Muñoz) "Customer Information template", sent 2026-11-10.
-- One governed table holds every dropdown of the sheet. Dependent lists carry their parents:
-- distribution channel / sales office / delivering plant -> sales_org_code;
-- Customer Grp 1 -> sales_org_code + channel_code; Customer Grp 2 -> + group1_code.
-- Codes are text exactly as SAP shows them ("0002", "ZC03", "1000", "10").
create table customer_reference_values (
  id uuid primary key default gen_random_uuid(),
  list text not null check (list in (${REFERENCE_LISTS.map(lit).join(",")})),
  sales_org_code text not null default '',
  channel_code text not null default '',
  group1_code text not null default '',
  code text not null check (code <> ''),
  name text not null check (name <> ''),
  sort_order integer not null,
  active boolean not null default true,
  source text not null,
  updated_by text not null default 'system:customer-master',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  change_seq bigint not null default nextval('change_seq'),
  unique (list, sales_org_code, channel_code, group1_code, code)
);
create index customer_reference_values_lookup on customer_reference_values (list, sales_org_code, channel_code, group1_code, sort_order);
create trigger customer_reference_values_bump_change_seq before update on customer_reference_values for each row execute function bump_change_seq();

insert into customer_reference_values(list,sales_org_code,channel_code,group1_code,code,name,sort_order,source) 
select v.list,v.sales_org_code,v.channel_code,v.group1_code,v.code,v.name,v.sort_order,${lit(REFERENCE_SOURCE)} from (values
${values}
) as v(list,sales_org_code,channel_code,group1_code,code,name,sort_order);

insert into audit_logs(subject,action,entity_type,entity_id,details)
values('system:migration','customer_master.reference.load','customer_reference_values',${lit(REFERENCE_SOURCE)},'{"rows":${rows.length}}');
`;
}

if (import.meta.main) {
  const sql = await buildSql();
  if (process.argv.includes("--check")) {
    const current = await Bun.file(MIGRATION).text();
    if (current !== sql) {
      console.error("0820_customer_master_reference.sql is stale; rebuild it");
      process.exit(1);
    }
    console.log("up to date");
  } else {
    await Bun.write(MIGRATION, sql);
    console.log(`wrote ${MIGRATION}`);
  }
}
