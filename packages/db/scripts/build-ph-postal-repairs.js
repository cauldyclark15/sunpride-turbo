// SP-0242: generate the additive postal repair for already populated installations.
// Fresh installs get the same reviewed rows through loadPhGeography.
// Run with --check to verify the committed SQL; never rewrite an applied repair.
import {
  geographyRelease,
  POSTAL_REPAIRS_FILE,
  readGeographyJson,
} from "../src/ph-geography.js";

const repairs = JSON.parse(await Bun.file(POSTAL_REPAIRS_FILE).text());
const geography = await readGeographyJson(); // validates every reviewed mapping
const target = new URL(
  "../migrations/0849_ph_postal_repairs.sql",
  import.meta.url,
);
/** @param {any} value */
const literal = (value) =>
  value == null ? "null" : `'${String(value).replaceAll("'", "''")}'`;
const values = repairs.postalCodes.map((/** @type {any} */ r) =>
  [r.municipalityCode, r.postalCode, r.area, r.source].map(literal).join(","),
);
const metadata = {
  postalRevision: geography.source.postalRevision,
  postalRepairs: geography.source.postalRepairs,
};
const sql = `-- Generated by packages/db/scripts/build-ph-postal-repairs.js (SP-0242).
-- Reviewed government sources and unresolved places: reference/ph-postal-repairs-sp242.json.
-- Add missing keys only; preserve every existing entry and all customer records.
-- Empty installations are populated later by the geography seed, not by this repair.
select pg_advisory_xact_lock(4310170);
with reviewed(municipality_code,postal_code,area,source) as (
  values
${values.map((/** @type {string} */ row) => `    (${row})`).join(",\n")}
), added as (
  insert into ph_postal_codes(municipality_code,postal_code,area,source)
  select r.municipality_code,r.postal_code,r.area,r.source
  from reviewed r join ph_municipalities m on m.code=r.municipality_code
  on conflict(municipality_code,postal_code) do nothing
  returning 1
)
insert into audit_logs(subject,action,entity_type,entity_id,details)
select 'system:postal-sp242','customer_master.geography.postal_repair','ph_geography_releases',
  ${literal(repairs.revision)},jsonb_build_object('added',count(*))
from added having count(*) > 0;

insert into ph_geography_releases(release,source,counts,loaded_by)
select ${literal(geographyRelease(geography))},
  source || ${literal(JSON.stringify(metadata))}::jsonb,
  counts || jsonb_build_object(
    'postalCodes',(select count(*)::int from ph_postal_codes),
    'municipalitiesWithPostal',(select count(distinct municipality_code)::int from ph_postal_codes)),
  'system:postal-sp242'
from ph_geography_releases where release=${literal(geography.source.psgc.release)}
on conflict(release) do nothing;
`;
if (process.argv.includes("--check")) {
  if ((await Bun.file(target).text()) !== sql)
    throw new Error("Postal repair SQL differs from its reviewed reference");
  console.log(
    `Postal repair SQL matches ${repairs.postalCodes.length} reviewed rows.`,
  );
} else {
  await Bun.write(target, sql);
  console.log(
    `Generated ${repairs.postalCodes.length} reviewed postal additions.`,
  );
}
